let current = 'es';
const listeners = new Set();

/** Normaliza un idioma a uno soportado. */
function normalize(lang) {
  const value = String(lang || '').toLowerCase().slice(0, 2);
  return Object.prototype.hasOwnProperty.call(DICT, value) ? value : 'es';
}

/** Fija el idioma activo y avisa a los suscriptores. */
export function setLanguage(lang) {
  const next = normalize(lang);
  if (next === current) return next;
  current = next;
  document.documentElement.lang = next;
  listeners.forEach((fn) => fn(next));
  return next;
}

export function getLanguage() {
  return current;
}

export function onLanguageChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function availableLanguages() {
  return Object.keys(DICT);
}

/**
 * Traduce una clave. Sustituye los marcadores `{nombre}` por `params.nombre`.
 * Si la clave no existe devuelve la propia clave (facilita detectar huecos).
 */
export function t(key, params) {
  const table = DICT[current] || DICT.es;
  let text = table[key];
  if (text === undefined) text = DICT.es[key];
  if (text === undefined) return key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ));
}

/**
 * Aplica las traducciones a un subárbol:
 *  - `data-i18n="clave"`            → textContent
 *  - `data-i18n-attr="attr:clave"`  → atributo (varios separados por ';')
 */
export function applyTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-attr]').forEach((node) => {
    node.getAttribute('data-i18n-attr').split(';').forEach((pair) => {
      const [attr, key] = pair.split(':').map((part) => (part || '').trim());
      if (attr && key) node.setAttribute(attr, t(key));
    });
  });
}

export default { t, setLanguage, getLanguage, onLanguageChange, applyTranslations, availableLanguages };
